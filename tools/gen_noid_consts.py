#!/usr/bin/env python3
"""Generates src/algo/noid/noid_consts.hpp from the official Parano1d sources (Apache-2.0).

    python tools/gen_noid_consts.py <parano1d checkout>

Reads noid_core/src/hardware.rs (TOWER_TO_FLAT, FLAT_TO_TOWER) and noid_poseidon2b/src/native/permutation.rs
(ROUND_CONSTANTS, MDS_FULL, MDS_PARTIAL) and emits them with flat-basis versions of the round and MDS constants.
"""
import re, sys, subprocess, os

root = sys.argv[1]
hw = open(os.path.join(root, "noid_core/src/hardware.rs"), encoding="utf-8").read()
pm = open(os.path.join(root, "noid_poseidon2b/src/native/permutation.rs"), encoding="utf-8").read()
try:
    commit = subprocess.check_output(["git", "-C", root, "rev-parse", "--short", "HEAD"], text=True).strip()
except Exception:
    commit = "unknown"

def arr(name):
    m = re.search(name + r": \[u128; 128\] = \[(.*?)\];", hw, re.S)
    return [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", m.group(1))]

def blk(name):
    m = re.search(name + r"[^=]*= \[(.*?)\n\];", pm, re.S)
    return [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", m.group(1))]

T2F, F2T = arr("TOWER_TO_FLAT"), arr("FLAT_TO_TOWER")
assert len(T2F) == 128 and len(F2T) == 128
RC = blk("ROUND_CONSTANTS"); assert len(RC) == 4 * 66
MF = blk("MDS_FULL"); assert len(MF) == 16
MP = blk("MDS_PARTIAL"); assert len(MP) == 16

def lin(M, v):
    r, i = 0, 0
    while v:
        if v & 1: r ^= M[i]
        v >>= 1; i += 1
    return r

def u128(v):
    return "{0x%016xull, 0x%016xull}" % (v & (2**64 - 1), v >> 64)

out = []
out.append("// Generated by tools/gen_noid_consts.py from github.com/ignotusnemo/parano1d @%s (Apache-2.0)." % commit)
out.append("// Sources: noid_core/src/hardware.rs, noid_poseidon2b/src/native/permutation.rs. Do not edit.")
out.append("// Copyright 2026 Paranoid Zero; see THIRD_PARTY.md for the NOTICE.")
out.append("#pragma once\n#include <cstdint>\n\nnamespace xm::noid {\n\nstruct U128c {\n  uint64_t lo, hi;\n};\n")
out.append("// Basis maps: entry i is the image of bit i.")
out.append("inline constexpr U128c kTowerToFlat[128] = {\n" + ",\n".join("    " + u128(v) for v in T2F) + "};")
out.append("inline constexpr U128c kFlatToTower[128] = {\n" + ",\n".join("    " + u128(v) for v in F2T) + "};")
out.append("// Round constants in the flat basis: [state lane][round].")
out.append("inline constexpr U128c kRoundConstFlat[4][66] = {\n" +
           ",\n".join("    {" + ", ".join(u128(lin(T2F, RC[i * 66 + r])) for r in range(66)) + "}" for i in range(4)) + "};")
out.append("// MDS matrices: raw tower integers (1 = plain XOR) and flat-basis multipliers.")
out.append("inline constexpr uint32_t kMdsFullTower[4][4] = {" + ", ".join("{" + ", ".join(str(MF[i * 4 + j]) for j in range(4)) + "}" for i in range(4)) + "};")
out.append("inline constexpr uint32_t kMdsPartialTower[4][4] = {" + ", ".join("{" + ", ".join(str(MP[i * 4 + j]) for j in range(4)) + "}" for i in range(4)) + "};")
out.append("inline constexpr U128c kMdsFullFlat[4][4] = {" + ", ".join("{" + ", ".join(u128(lin(T2F, MF[i * 4 + j])) for j in range(4)) + "}" for i in range(4)) + "};")
out.append("inline constexpr U128c kMdsPartialFlat[4][4] = {" + ", ".join("{" + ", ".join(u128(lin(T2F, MP[i * 4 + j])) for j in range(4)) + "}" for i in range(4)) + "};")
lab = int.from_bytes(b"POWHDR__", "big")
out.append("// Sponge IV (capacity lanes) for the POWHDR__ domain, flat basis.")
out.append("inline constexpr U128c kIvFlat[2] = {%s, %s};" % (u128(lin(T2F, lab << 64)), u128(lin(T2F, lab))))
out.append("\n}  // namespace xm::noid")
open("src/algo/noid/noid_consts.hpp", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("wrote src/algo/noid/noid_consts.hpp", commit)
